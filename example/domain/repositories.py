from typing import Protocol
from uuid import UUID

from example.domain.dormitory import Dormitory
from example.domain.student import Student


class StudentRepository(Protocol):
    async def get(self, student_id: UUID) -> Student | None: ...
    async def get_for_share(self, student_id: UUID) -> Student | None: ...
    async def list(self, *, offset: int = 0, limit: int = 100): ...
    async def exists_by_number(self, student_no: str) -> bool: ...
    def add(self, student: Student) -> None: ...
    async def remove(self, student: Student) -> None: ...


class DormitoryRepository(Protocol):
    async def get(self, dormitory_id: UUID) -> Dormitory | None: ...
    async def get_for_update(self, dormitory_id: UUID) -> Dormitory | None: ...
    async def get_for_share(self, dormitory_id: UUID) -> Dormitory | None: ...
    async def list(self, *, offset: int = 0, limit: int = 100): ...
    async def find_by_student_id(self, student_id: UUID) -> Dormitory | None: ...
    def add(self, dormitory: Dormitory) -> None: ...
    async def remove(self, dormitory: Dormitory) -> None: ...
